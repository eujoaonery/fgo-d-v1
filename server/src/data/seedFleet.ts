function healthFor(status: CadastralStatus): number {
  if (status === 'em_manutencao') return 45
  if (status === 'em_uso') return 90
  if (status === 'desativado') return 0
  return 100
}

export function seedFleetAssets(now = new Date().toISOString()): UrbanAsset[] {
  return FLEET.map((spec) => ({
    id: spec.id,
    name: spec.name,
    category: spec.category,
    subtype: spec.subtype,
    region: spec.region,
    status: spec.cadastralStatus === 'desativado' ? 'inativo' : 'operacional',
    cadastralStatus: spec.cadastralStatus,
    health: healthFor(spec.cadastralStatus),
    lastSeen: now,
    serialNumber: spec.plate,
    patrimonyCode: spec.patrimony,
    manufacturer: spec.manufacturer,
    model: spec.model,
    responsibleOrg: spec.org,
    responsibleTeam: spec.team,
    criticality: spec.criticality,
    dataOrigin: 'simulado',
    installedAt: '2023-02-10',
    acquiredAt: '2023-01-20',
    maintenanceIntervalDays: 90,
    usefulLifeMonths: spec.usefulLifeMonths,
    notes: 'Veículo da frota municipal de demonstração.',
    location: {
      cep: spec.cep,
      neighborhood: spec.neighborhood,
      city: 'Marília',
      uf: 'SP',
      street: spec.street,
      number: spec.number,
      reference: 'Base operacional',
      referenceKind: 'numero',
      locationType: 'recurso_movel',
    },
  }))
}
